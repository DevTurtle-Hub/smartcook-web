import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';

const source = readFileSync(new URL('../src/utils/storeMaps.ts', import.meta.url), 'utf8');
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } });
const { storeDirectionsUrl, storeSearchUrl, validMapCoordinates } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
const destination = { lat: 16.0544, lng: 108.2022 };
let url = new URL(storeDirectionsUrl(destination));
assert.equal(url.origin, 'https://www.google.com');
assert.equal(url.searchParams.get('api'), '1');
assert.equal(url.searchParams.get('destination'), '16.0544,108.2022');
assert.equal(url.searchParams.has('origin'), false, 'A selected city is not the user’s actual GPS origin');
url = new URL(storeDirectionsUrl(destination, { lat: 10.7769, lng: 106.7009 }, 'two-wheeler'));
assert.equal(url.searchParams.get('origin'), '10.7769,106.7009');
assert.equal(url.searchParams.get('travelmode'), 'two-wheeler');
assert.equal(new URL(storeDirectionsUrl(destination, undefined, 'walking')).searchParams.get('travelmode'), 'walking');
assert.equal(validMapCoordinates(0, 0), true);
assert.equal(validMapCoordinates(91, 108), false);
assert.equal(validMapCoordinates(16, NaN), false);
assert.throws(() => storeDirectionsUrl({ lat: 0, lng: 181 }));
const query = 'Siêu thị & chợ tại Đà Nẵng';
assert.equal(new URL(storeSearchUrl(query)).searchParams.get('query'), query);
assert.equal(new URL(storeSearchUrl('')).searchParams.get('query'), 'Siêu thị gần tôi');
console.log('PASS: Google Maps search, encoded Vietnamese queries, GPS versus area origins, travel modes and invalid-coordinate handling.');

const campusSource = readFileSync(new URL('../src/utils/quyNhonStores.ts', import.meta.url), 'utf8');
const campusJs = ts.transpileModule(campusSource, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText;
const { FPT_QUY_NHON, quyNhonStoresNear } = await import('data:text/javascript;base64,' + Buffer.from(campusJs).toString('base64'));
const nearby = quyNhonStoresNear(FPT_QUY_NHON, 10);
assert.equal(nearby.length, 4);
assert.equal(nearby[0].name, 'Siêu thị Gia Đình');
assert.equal(nearby[0].distanceKm, 1.4);
assert.equal(quyNhonStoresNear(FPT_QUY_NHON, 1).length, 0);
assert.equal(quyNhonStoresNear(FPT_QUY_NHON, 5).length, 3);
assert.ok(nearby.every((store, i) => !i || store.distanceKm >= nearby[i - 1].distanceKm));
const campusRoute = new URL(storeDirectionsUrl({lat: nearby[0].latitude, lng: nearby[0].longitude}, FPT_QUY_NHON));
assert.equal(campusRoute.searchParams.get('origin'), '13.8038844,109.2191454');
console.log('PASS: verified campus origin, nearby-store ordering and radius filtering without device geolocation.');
