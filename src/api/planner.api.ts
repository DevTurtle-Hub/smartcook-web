import { apiClient } from './client';
import type { ApiResponse } from '../types';

export interface PlannerMealSlot {
  _id?: string;
  slot: 'Bữa Sáng' | 'Bữa Trưa' | 'Bữa Tối' | 'Bữa Phụ';
  time: string;
  calories: number;
  isCooked: boolean;
  notes?: string;
  customTitle?: string;
  recipe?: {
    id: string;
    title: string;
    image: string;
    minutes: number;
    difficulty: string;
    calories: number;
    rating: number;
  };
}

export interface PlannerDay {
  dayOfWeek: string;
  date: string;
  dailyCalories: number;
  mealsCount: number;
  meals: PlannerMealSlot[];
}

export interface WeeklyPlanData {
  _id: string;
  weekStartDate: string;
  totalWeekCalories: number;
  days: PlannerDay[];
}

export interface ShoppingItemData {
  _id: string;
  id?: string;
  name: string;
  amount: string;
  price: number;
  category: string;
  recipeTitle?: string;
  bought: boolean;
  isAutoGenerated: boolean;
}

export interface ShoppingListData {
  weekStartDate: string;
  items: ShoppingItemData[];
  estimatedTotalCost: number;
  totalItemsCount: number;
  unboughtCount: number;
  boughtCount: number;
  fridgeItemsExcludedCount: number;
}

export const plannerApi = {
  getWeeklyPlan: async (weekDate?: string): Promise<WeeklyPlanData | null> => {
    try {
      const res = await apiClient.get<ApiResponse<WeeklyPlanData>>('/planner/current-week', {
        params: weekDate ? { weekDate } : undefined,
      });
      return res.data.data;
    } catch (err: any) {
      console.warn('[SmartCook Web] getWeeklyPlan error:', err.message);
      return null;
    }
  },

  setMealSlot: async (data: {
    weekDate?: string;
    dayOfWeek: string;
    slot: 'Bữa Sáng' | 'Bữa Trưa' | 'Bữa Tối' | 'Bữa Phụ';
    time?: string;
    recipeId?: string;
    customTitle?: string;
    calories?: number;
    isCooked?: boolean;
    notes?: string;
  }): Promise<WeeklyPlanData | null> => {
    try {
      const res = await apiClient.put<ApiResponse<WeeklyPlanData>>('/planner/meals', data);
      return res.data.data;
    } catch (err: any) {
      console.warn('[SmartCook Web] setMealSlot error:', err.message);
      return null;
    }
  },

  getShoppingList: async (weekDate?: string): Promise<ShoppingListData | null> => {
    try {
      const res = await apiClient.get<ApiResponse<ShoppingListData>>('/planner/shopping-list', {
        params: weekDate ? { weekDate } : undefined,
      });
      return res.data.data;
    } catch (err: any) {
      console.warn('[SmartCook Web] getShoppingList error:', err.message);
      return null;
    }
  },

  toggleBought: async (itemId: string, bought: boolean): Promise<ShoppingItemData | null> => {
    try {
      const res = await apiClient.patch<ApiResponse<ShoppingItemData>>(
        `/planner/shopping-list/${itemId}/bought`,
        { bought }
      );
      return res.data.data;
    } catch (err: any) {
      console.warn('[SmartCook Web] toggleBought error:', err.message);
      return null;
    }
  },

  syncToFridge: async (): Promise<{ syncedCount: number; totalFridgeItems: number } | null> => {
    try {
      const res = await apiClient.post<ApiResponse<any>>('/planner/sync-to-fridge');
      return res.data.data;
    } catch (err: any) {
      console.warn('[SmartCook Web] syncToFridge error:', err.message);
      return null;
    }
  },
};
